# ======== 逐段扫描收集 evidence ========
def scan_entity(ent, text):
    """若ent的name或任意alias在text中出现，则返回True。"""
    names = [ent["name"]] + ent.get("alias", [])
    for n in names:
        if not n: continue
        # 取核心名称（去掉括号里的内容）匹配
        core = n.split("（")[0].split("(")[0]
        if core and core in text:
            return True
    return False

